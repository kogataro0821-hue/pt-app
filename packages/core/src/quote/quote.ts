/**
 * ログイン画面の前に出す言葉（追加仕様: 導入の演出）。
 *
 * ★ 実在の人の名言は、載せていません。
 *
 *   筋トレ・ダイエットの世界に流れている「◯◯の言葉」は、
 *   本人が言っていないものが本当に多いです。出典不明のまま
 *   アプリに刷ると、その責任はこちら側になります。
 *   **このアプリのために書いた言葉だけ**を置いています。
 *   誰の名前も付けません。
 *
 * ★ 内容には枠を決めてあります。
 *
 *   ・自分を責めさせない（「甘え」「怠け」のような言い方はしない）
 *   ・極端を勧めない（絶食・過度な運動・体重の目標値を煽らない）
 *   ・休んだ日を否定しない
 *
 *   記録アプリを開くたびに責められるのは、続ける妨げになります。
 *   ここは毎日目に入る場所なので、いちばん気をつけるところです。
 *
 * ★ 3行に分けて持ちます。
 *
 *   画面側で折り返させるのではなく、**どこで切るかをこちらで決めます**。
 *   1行ずつ浮かび上がる作りなので、切れ目が意味の切れ目と
 *   合っていないと、読んでいて引っかかります。
 *   端末の幅によって切れ目が変わるのも防げます。
 *
 * ★ 句点（。）は使いません。
 *
 *   浮かび上がる文字の最後に丸が付くと、そこだけ重く見えます。
 *   1つだけ残っても浮くので、まるごと使いません。
 *   区切りたいところは「、」でつなぎます。
 *
 * ★ アプリに同梱しています。通信では取ってきません。
 *
 *   ログイン前は Firestore から何も読めません（Rules でそう締めています）。
 *   だから管理者が後から書き換える形にはできません。
 *   差し替えるときは、このファイルを直します。
 */

/** 1つの言葉。3行で持ちます。 */
export type Quote = readonly [string, string, string];

export const QUOTES: readonly Quote[] = [
  ['速さより、続くかどうか', '小さく積んだものだけが', 'あとから形になる'],
  ['食べたものを知ることが', 'いちばん効く', '記録は、そのための道具'],
  ['休んだ日も', 'やめた日ではない', '戻ってきた人が、いちばん伸びる'],
  ['体重は毎日ぶれる', 'その日の数字ではなく', 'ひと月の流れを見る'],
  ['完璧な一日より', 'ふつうの一週間', 'それが積み上がっていく'],
  ['減らすことより', '整えること', '続けられる形を探す'],
  ['迷ったら、まず書く', '書けば見えて', '見えれば直せる'],
  ['体は、あなたが選んだもので', 'できている', '今日の一食も、その一部'],
  ['できなかった日を数えず', 'できた日を数える', 'それだけで前に進む'],
  ['はじめる日は、いつも今日', '昨日の自分と比べて', '少しだけでいい'],
];

/**
 * その日の言葉。
 *
 * ★ 日替わりにしています。開くたびに変えていません。
 *
 *   開くたびに変わると、くじを引いている感じになって
 *   言葉そのものが軽くなります。1日1つなら、
 *   同じ日に開いた人同士が同じ言葉を見ます。
 *
 * ★ 同じ日付なら、必ず同じ言葉が返ります。
 *   端末が違っても、読み込み直しても変わりません。
 */
export function quoteOfDay(dateKey: string): Quote {
  const fallback: Quote = QUOTES[0] ?? ['', '', ''];
  if (QUOTES.length === 0) return fallback;

  // ★ 文字を足すだけの計算では駄目でした。
  //
  //   最初は「文字コードを足して、言葉の数で割った余り」にしていました。
  //   ところが日付は1日で下1桁が1しか動かず、位の重みを掛けたぶんだけ
  //   ちょうど言葉の数の倍数ずれることがあり、**次の日も同じ言葉**に
  //   なっていました（言葉が10個のとき、まさにそうなりました）。
  //
  //   1日動いたら結果が散らばる必要があるので、掛けて混ぜる形にします。
  //   暗号の用途ではないので、短くて充分に散らばるものを使います。
  let hash = 2166136261;
  for (let i = 0; i < dateKey.length; i += 1) {
    hash ^= dateKey.charCodeAt(i);
    // 32bit に収めながら混ぜます（>>> 0 で符号なしに戻す）
    hash = Math.imul(hash, 16777619) >>> 0;
  }
  return QUOTES[hash % QUOTES.length] ?? fallback;
}

/** 読み上げ用に、3行をひとつなぎにする。 */
export function quoteToText(quote: Quote): string {
  return quote.join(' ');
}
